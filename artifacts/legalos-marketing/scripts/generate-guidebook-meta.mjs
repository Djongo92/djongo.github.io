#!/usr/bin/env node
// Regenerates src/data/guidebookMeta.ts from the app's canonical chapter
// registry — artifacts/legalos/src/data/chapters/ (one file per chapter;
// types.ts and *.test.ts are not chapters). The web chapters dir is the
// single source of truth (mobile's chapters.ts is generated from it too),
// so the marketing site's "N-chapter guidebook" copy is derived, never
// hand-written: dev/build auto-regenerates, and check:guidebook fails if
// the committed file is behind the registry.

import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const CHAPTERS_DIR = resolve(here, "../../legalos/src/data/chapters");
const OUT = join(here, "../src/data/guidebookMeta.ts");

/** Counts real chapter files: *.ts minus types.ts (shared types) and *.test.ts. */
export function countChapters(fileNames) {
  return fileNames.filter(
    (n) => n.endsWith(".ts") && n !== "types.ts" && !n.endsWith(".test.ts"),
  ).length;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const count = countChapters(readdirSync(CHAPTERS_DIR));
  if (count === 0) {
    console.error(`ERROR: no chapter files found in ${CHAPTERS_DIR} — is the path still right?`);
    process.exit(1);
  }
  writeFileSync(
    OUT,
    `// AUTO-GENERATED by scripts/generate-guidebook-meta.mjs — do not edit by hand.
// Source of truth: artifacts/legalos/src/data/chapters/ (one file per chapter,
// types.ts excluded). Regenerate: pnpm run generate:guidebook (also runs
// automatically before dev/build).

export const GUIDEBOOK_CHAPTER_COUNT = ${count};
`,
  );
  console.log(`guidebookMeta.ts: ${count} chapters`);
}
