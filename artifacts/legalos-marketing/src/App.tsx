function useLegalRoute(): 'privacy' | 'terms' | 'dpa' | null {
  const read = () => {
    const h = window.location.hash;
    if (h === '#/privacy') return 'privacy' as const;
    if (h === '#/terms') return 'terms' as const;
    if (h === '#/dpa') return 'dpa' as const;
    return null;
  };
  const [route, setRoute] = useState<'privacy' | 'terms' | 'dpa' | null>(read);
  useEffect(() => {
    const onHash = () => {
      setRoute(read());
      if (read()) window.scrollTo(0, 0);
    };
    window.addEventListener('hashchange', onHash);
    return () => window.removeEventListener('hashchange', onHash);
  }, []);
  return route;
}

